package com.quarkdown.processor.generation

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.quarkdown.processor.model.FunctionDescriptor
import com.quarkdown.processor.model.ModuleDescriptor
import com.quarkdown.processor.util.ModuleNaming
import com.quarkdown.processor.util.backtick
import com.quarkdown.processor.util.backtickLastSegment

/**
 * Emits one Kotlin source file per discovered [ModuleDescriptor]: an `object <ModuleName>`
 * containing synthetic wrappers around the source `@QFunction`s and a nested `QuarkdownModule` declaration.
 */
class ModuleCodeGenerator(
    private val codeGenerator: CodeGenerator,
) {
    fun generate(module: ModuleDescriptor) {
        val dependencies = Dependencies(aggregating = false, module.file)
        val fileName = ModuleNaming.generatedFileNameOf(module.name)
        codeGenerator
            .createNewFile(dependencies, module.packageName, fileName, extensionName = ModuleNaming.KOTLIN_EXTENSION)
            .bufferedWriter()
            .use { it.write(render(module)) }
    }

    private fun render(module: ModuleDescriptor): String =
        KotlinSource()
            .apply {
                emitFileHeader(module)
                block("object ${module.name} {") {
                    emitModuleVal(module)
                    module.functions.forEach { function ->
                        blank()
                        emitWrapper(function)
                    }
                }
            }.toString()

    private fun KotlinSource.emitFileHeader(module: ModuleDescriptor) {
        line("// Generated by quarkdown-native-library-processor. Do not edit.")
        commaList("@file:Suppress(", FILE_SUPPRESS.map { "\"$it\"" }, ")")
        blank()
        line("package ${module.packageName}")
        blank()
        line("import $QUARKDOWN_MODULE_FQN")
        line("import $MODULE_OF_FQN")
        module.sourceImports?.let {
            blank()
            lines(it)
        }
        blank()
    }

    private fun KotlinSource.emitModuleVal(module: ModuleDescriptor) {
        line("val Module: QuarkdownModule =")
        indent {
            commaList(
                "moduleOf(",
                module.functions.map { "this::${it.exportedName.backtick()}" },
                ")",
            )
        }
    }

    /**
     * Emits the public typed wrapper: KDoc, propagated function-level annotations, the fun
     * signature, and a single-expression body that delegates to the source function under its FQN.
     */
    private fun KotlinSource.emitWrapper(function: FunctionDescriptor) {
        KDocComposer.compose(function)?.let { emitKDoc(it) }
        function.sourceAnnotations?.let(::line)
        val signature =
            function.parameters
                .flatParameters
                .joinToString(", ") { it.wrapperSignatureEntry() }
        val returnType = KSTypeRenderer.render(function.returnType)
        val delegation = function.parameters.joinToString(", ") { it.delegationArgument }
        line("public fun ${function.exportedName.backtick()}($signature): $returnType =")
        indent { line("${function.qualifiedName.backtickLastSegment()}($delegation)") }
    }

    /**
     * Emits [rawKDoc] as a `/** … */` block at the current depth. Each source line becomes a
     * `* <line>` entry; blank source lines are preserved as blank comment lines so Dokka sees
     * paragraph boundaries.
     */
    private fun KotlinSource.emitKDoc(rawKDoc: String) {
        line("/**")
        rawKDoc.lines().forEach { raw ->
            val trimmed = raw.trimEnd().replace("*/", "*\\/")
            if (trimmed.isEmpty()) line(" *") else line(" * $trimmed")
        }
        line(" */")
    }

    private companion object {
        const val QUARKDOWN_MODULE_FQN = "com.quarkdown.core.function.library.module.QuarkdownModule"
        const val MODULE_OF_FQN = "com.quarkdown.core.function.library.module.moduleOf"

        /**
         * File-level [Suppress] annotation entries applied to every generated source.
         */
        val FILE_SUPPRESS =
            listOf(
                "RedundantVisibilityModifier",
                "RemoveRedundantBackticks",
                "unused",
                "ktlint:standard:annotation",
                "ktlint:standard:argument-list-wrapping",
                "ktlint:standard:chain-method-continuation",
                "ktlint:standard:filename",
                "ktlint:standard:function-naming",
                "ktlint:standard:function-signature",
                "ktlint:standard:import-ordering",
                "ktlint:standard:indent",
                "ktlint:standard:max-line-length",
                "ktlint:standard:no-unused-imports",
                "ktlint:standard:parameter-list-wrapping",
                "ktlint:standard:parameter-wrapping",
                "ktlint:standard:paren-spacing",
            )
    }
}
