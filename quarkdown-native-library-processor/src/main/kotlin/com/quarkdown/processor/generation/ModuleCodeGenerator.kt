package com.quarkdown.processor.generation

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.quarkdown.processor.model.DocumentTypeConstraint
import com.quarkdown.processor.model.FunctionDescriptor
import com.quarkdown.processor.model.ModuleDescriptor
import com.quarkdown.processor.model.ParameterDescriptor
import com.quarkdown.processor.util.ModuleNaming
import com.quarkdown.processor.util.backtick
import com.quarkdown.processor.util.backtickLastSegment

/**
 * Emits one Kotlin source file per discovered [ModuleDescriptor], containing:
 *
 * - a public wrapper `fun <name>(...)` per `@QFunction`, preserving the source signature and KDoc
 *   so Quarkdoc can document the module by inspecting the wrapper object;
 * - a pre-built `internal val <name>__function: Function<T>` per `@QFunction`, whose
 *   [com.quarkdown.core.function.SimpleFunction] holds baked-at-codegen parameter metadata and
 *   an invoke lambda that dispatches to the source function without going through
 *   [com.quarkdown.core.function.reflect.KFunctionAdapter];
 * - a `val Module: QuarkdownModule = moduleOf(<name>__function, ...)` that registers those
 *   function values with the runtime.
 */
class ModuleCodeGenerator(
    private val codeGenerator: CodeGenerator,
) {
    fun generate(module: ModuleDescriptor) {
        val dependencies = Dependencies(aggregating = false, module.file)
        val fileName = ModuleNaming.generatedFileNameOf(module.name)
        codeGenerator
            .createNewFile(dependencies, module.packageName, fileName, extensionName = ModuleNaming.KOTLIN_EXTENSION)
            .bufferedWriter()
            .use { it.write(render(module)) }
    }

    private fun render(module: ModuleDescriptor): String =
        KotlinSource()
            .apply {
                emitFileHeader(module)
                block("object ${module.name} {") {
                    module.functions.forEach { function ->
                        emitWrapper(function)
                        blank()
                        emitFunctionValue(function)
                        blank()
                    }
                    emitModuleVal(module)
                }
            }.toString()

    private fun KotlinSource.emitFileHeader(module: ModuleDescriptor) {
        line("// Generated by quarkdown-native-library-processor. Do not edit.")
        commaList("@file:Suppress(", FILE_SUPPRESS.map { "\"$it\"" }, ")")
        blank()
        line("package ${module.packageName}")
        blank()
        line("import ${Fqns.quarkdownModule}")
        line("import ${Fqns.moduleOf}")
        module.sourceImports?.let {
            blank()
            lines(it)
        }
        blank()
    }

    private fun KotlinSource.emitModuleVal(module: ModuleDescriptor) {
        line("val Module: QuarkdownModule =")
        indent {
            if (module.functions.isEmpty()) {
                line("QuarkdownModule()")
            } else {
                commaList(
                    "moduleOf(",
                    module.functions.map { functionValueName(it).backtick() },
                    ")",
                )
            }
        }
    }

    /**
     * Emits the public typed wrapper: KDoc, propagated function-level annotations, the fun
     * signature, and a single-expression body that delegates to the source function under its FQN.
     */
    private fun KotlinSource.emitWrapper(function: FunctionDescriptor) {
        KDocComposer.compose(function)?.let { emitKDoc(it) }
        function.sourceAnnotations?.let(::line)
        val signature =
            function.parameters
                .flatParameters
                .joinToString(", ") { it.wrapperSignatureEntry() }
        val returnType = KSTypeRenderer.render(function.returnType)
        val delegation =
            function.parameters.joinToString(", ") { it.delegationArgument }
        line("public fun ${function.exportedName.backtick()}($signature): $returnType =")
        indent { line("${function.qualifiedName.backtickLastSegment()}($delegation)") }
    }

    /**
     * Emits the pre-built [com.quarkdown.core.function.library.loader.ExportableFunction]
     * `SimpleFunction(...)` literal.
     */
    private fun KotlinSource.emitFunctionValue(function: FunctionDescriptor) {
        val flatParams = function.parameters.flatParameters
        val returnType = KSTypeRenderer.render(function.returnType)
        line("internal val ${functionValueName(function).backtick()}: ${Fqns.function}<$returnType> =")
        indent {
            block("${Fqns.simpleFunction}(", ")") {
                line("name = \"${function.exportedName}\",")
                commaList(
                    "parameters = listOf(",
                    flatParams.mapIndexed { i, p -> p.functionParameterLiteral(i) },
                    "),",
                )
                emitValidators(function.documentTypeConstraint, returnType)
                emitInvokeLambda(function, flatParams)
            }
        }
    }

    /**
     * Emits `validators = listOf(DocumentTypeFunctionCallValidator(setOf(DocumentType.X, ...)))`
     * when the source function carries a `@OnlyForDocumentType` / `@NotForDocumentType`
     * annotation, or `validators = emptyList()` otherwise.
     */
    private fun KotlinSource.emitValidators(
        constraint: DocumentTypeConstraint?,
        returnType: String,
    ) {
        if (constraint == null) {
            line("validators = emptyList(),")
            return
        }
        val allowedTypes = constraint.allowedTypes.joinToString(", ") { "${Fqns.documentType}.$it" }
        commaList(
            "validators = listOf(",
            listOf("${Fqns.documentTypeFunctionCallValidator}<$returnType>(setOf($allowedTypes))"),
            "),",
        )
    }

    /**
     * Emits the invoke lambda:
     * 1. copy each argument from `bindings` into a positional `slots` array
     * 2. materialize a typed local per flat parameter
     * 3. delegate to the source function inside a `try/catch` that rethrows `PipelineException`
     */
    private fun KotlinSource.emitInvokeLambda(
        function: FunctionDescriptor,
        flatParams: List<ParameterDescriptor.Plain>,
    ) {
        val slotCount = flatParams.size
        val delegation = function.parameters.joinToString(", ") { it.delegationArgument }
        val sourceCall = "${function.qualifiedName.backtickLastSegment()}($delegation)"

        block("invoke = { bindings, call ->", "},") {
            line("val slots: Array<Any?> = arrayOfNulls<Any?>($slotCount)")
            line("val present: BooleanArray = BooleanArray($slotCount)")
            emitSlotPopulation()
            flatParams.forEachIndexed { i, p -> line(p.typedLocalDeclaration(i)) }
            emitTryCatchDelegation(sourceCall)
        }
    }

    private fun KotlinSource.emitSlotPopulation() {
        block("bindings.forEach { (p, a) ->", "}") {
            block("slots[p.index] = when (val v = a.value) {") {
                line("is ${Fqns.noneValue} -> null")
                line("is ${Fqns.dynamicValue} -> v")
                line("else -> v.unwrappedValue")
            }
            line("present[p.index] = true")
        }
    }

    private fun KotlinSource.emitTryCatchDelegation(sourceCall: String) {
        line("try {")
        indent { line(sourceCall) }
        line("} catch (e: ${Fqns.pipelineException}) {")
        indent { line("throw e") }
        line("} catch (e: Exception) {")
        indent { line("throw ${Fqns.functionCallRuntimeException}(call, e)") }
        line("}")
    }

    /**
     * Emits [rawKDoc] as a `/** … */` block at the current depth. Each source line becomes a
     * `* <line>` entry.
     */
    private fun KotlinSource.emitKDoc(rawKDoc: String) {
        line("/**")
        rawKDoc.lines().forEach { raw ->
            val trimmed = raw.trimEnd().replace("*/", "*\\/")
            if (trimmed.isEmpty()) line(" *") else line(" * $trimmed")
        }
        line(" */")
    }

    /**
     * Name of the pre-built [com.quarkdown.core.function.library.loader.ExportableFunction] `val` for a `@QFunction`.
     */
    private fun functionValueName(function: FunctionDescriptor): String = "${function.exportedName}$FUNCTION_VALUE_SUFFIX"

    private companion object {
        const val FUNCTION_VALUE_SUFFIX = "__function"

        /**
         * File-level [Suppress] annotation entries applied to every generated source.
         */
        val FILE_SUPPRESS =
            listOf(
                "RedundantExplicitType",
                "RedundantVisibilityModifier",
                "RemoveRedundantBackticks",
                "RemoveRedundantQualifierName",
                "KotlinConstantConditions",
                "UNCHECKED_CAST",
                "unused",
                "ktlint:standard:annotation",
                "ktlint:standard:argument-list-wrapping",
                "ktlint:standard:chain-method-continuation",
                "ktlint:standard:filename",
                "ktlint:standard:function-naming",
                "ktlint:standard:function-signature",
                "ktlint:standard:import-ordering",
                "ktlint:standard:indent",
                "ktlint:standard:max-line-length",
                "ktlint:standard:multiline-expression-wrapping",
                "ktlint:standard:no-unused-imports",
                "ktlint:standard:parameter-list-wrapping",
                "ktlint:standard:parameter-wrapping",
                "ktlint:standard:paren-spacing",
                "ktlint:standard:property-naming",
                "ktlint:standard:property-wrapping",
                "ktlint:standard:wrapping",
            )
    }
}
