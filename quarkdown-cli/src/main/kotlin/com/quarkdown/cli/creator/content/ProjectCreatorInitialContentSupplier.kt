package com.quarkdown.cli.creator.content

import com.quarkdown.core.pipeline.output.OutputResource
import com.quarkdown.template.TemplateProcessor

/**
 * Supplier of the initial content of a new Quarkdown project.
 * This includes:
 * - The content injected into the main file, below the document setup
 * - Additional resources (e.g. assets)
 * @see com.quarkdown.cli.creator.ProjectCreator
 */
interface ProjectCreatorInitialContentSupplier {
    /**
     * @param template the main file's template processor, carrying every placeholder value of the project
     *                 (name, document type, main file name, ...), which suppliers may render their own templates through
     * @return the initial content to inject into the main file, or `null` for none
     */
    fun createInitialContent(template: TemplateProcessor): CharSequence?

    /**
     * @return a collection of additional resources that are generated by this supplier.
     * This may include assets, additional files, etc.
     */
    fun createResources(): Set<OutputResource>
}
